  function createI18n(initialLanguage = 'id') {
    let language = initialLanguage === 'en' ? 'en' : 'id';
    function setLanguage(value) {
      if (!['id', 'en'].includes(value)) throw new Error('Unsupported language.');
      language = value;
    }
    function t(key, values = {}) {
      let text = language === 'en' ? messages[key] || key : key;
      if (language === 'en' && key === '{count} episode') text = Number(values.count) === 1 ? '{count} episode' : '{count} episodes';
      if (language === 'en' && key === '{count} season') text = Number(values.count) === 1 ? '{count} season' : '{count} seasons';
      return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
    }
    return { get language() { return language; }, setLanguage, t };
  }
